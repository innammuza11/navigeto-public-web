export function project(p: { lat: number; lon: number }): [number, number] {
  return [100 + (p.lon - 79.5) * 170, 55 + (9.85 - p.lat) * 130];
}
export function straightLineKm(a: Place, b: Place) {
  const rad = Math.PI / 180;
  const h = Math.sin((b.lat - a.lat) * rad / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin((b.lon - a.lon) * rad / 2) ** 2;
  return Math.round(6371 * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h)) * 10) / 10;
}

