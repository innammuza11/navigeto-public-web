#!/usr/bin/env python3
"""Generate src/app/readability.css: a text-size floor for the public site.

The editorial/tropical themes set many labels to 5-10px, which is unreadable on
phones (12 Nov 2026 audit: ~100 text elements under 11px on a tour page, some at
5px). This script scans the global theme stylesheets and, for every rule that
sets a font-size below FLOOR, emits the same selector inside the same @media/
@supports context with font-size raised to the floor. readability.css is
imported last, so each override only beats the exact rule it mirrors; rules that
are already >= FLOOR (for example desktop sizes) are never touched.

Map overlay labels (landmarks, markers, compass) get a smaller floor so the
illustrated map stays legible without labels covering the artwork. SVG <text>
sizes are in viewBox units and are skipped.

Re-run after editing the theme CSS:  python3 scripts/generate-readability-floor.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["src/app/globals.css", "src/app/tropical-motion.css", "src/app/editorial-theme.css", "src/app/brand-theme.css"]
OUT = ROOT / "src/app/readability.css"
FLOOR = 11.0
MAP_FLOOR = 9.0
MAP_LABELS = ("itinerary-landmark", "itinerary-atlas-marker", "itinerary-atlas-compass")


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def walk(css: str, i: int, context: list, out: list) -> int:
    """Parse rules from css[i:] until the matching '}' (or EOF)."""
    while i < len(css):
        j = css.find("{", i)
        k = css.find("}", i)
        if k != -1 and (j == -1 or k < j):
            return k + 1
        if j == -1:
            return len(css)
        prelude = css[i:j].strip()
        if prelude.startswith("@media") or prelude.startswith("@supports"):
            i = walk(css, j + 1, context + [prelude], out)
            continue
        if prelude.startswith("@"):
            # @keyframes, @font-face etc.: skip the whole block
            depth, p = 1, j + 1
            while depth and p < len(css):
                depth += {"{": 1, "}": -1}.get(css[p], 0)
                p += 1
            i = p
            continue
        end = css.find("}", j)
        body = css[j + 1 : end]
        out.append((tuple(context), prelude, body))
        i = end + 1
    return i


def main() -> None:
    # Every font-size declaration, in cascade (source) order.
    decls = []
    for src in SOURCES:
        rules: list = []
        walk(strip_comments((ROOT / src).read_text()), 0, [], rules)
        for context, selector, body in rules:
            values = re.findall(r"font-size:\s*([^;}]+)", body)
            if not values:
                continue
            # Key on each selector of a list, with combinators normalised, so
            # ".a > b" and ".a>b" (or a later grouped rule) replay as one.
            for part in selector.split(","):
                sel = re.sub(r"\s*([>+~])\s*", r"\1", re.sub(r"\s+", " ", part)).strip()
                if not sel or re.search(r"(^|[\s>])text\b", sel):
                    continue  # SVG <text>: viewBox units, not CSS pixels
                decls.append((context, sel, values[-1].strip()))

    def floor_for(sel: str) -> float:
        return MAP_FLOOR if any(m in sel for m in MAP_LABELS) else FLOOR

    def px(value: str):
        m = re.fullmatch(r"([0-9.]+)px(\s*!important)?", value)
        return float(m.group(1)) if m else None

    small = {sel for _, sel, v in decls if px(v) is not None and px(v) < floor_for(sel)}
    # Re-emit every declaration of an affected selector, in the same order and
    # @media context, floored. Replaying the whole sequence keeps each
    # breakpoint's winner the same as in the source, only never below the floor.
    lines = [
        "/* GENERATED by scripts/generate-readability-floor.py — do not edit by hand.",
        f" * Raises theme text below {FLOOR:g}px (map labels below {MAP_FLOOR:g}px) to a readable floor.",
        " * Imported last in src/app/layout.tsx. */",
    ]
    count = 0
    for context, sel, value in decls:
        if sel not in small:
            continue
        size = px(value)
        if size is not None and size < floor_for(sel):
            value = f"{floor_for(sel):g}px"
        rule = f"{sel}{{font-size:{value}}}"
        for wrapper in reversed(context):
            rule = f"{wrapper}{{{rule}}}"
        lines.append(rule)
        count += 1
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(small)} selectors, {count} rules")


if __name__ == "__main__":
    main()
